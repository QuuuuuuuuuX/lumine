@dataclass
class ShardReader:
    paths: list[Path]

    @classmethod
    def discover(cls, root: str | Path, stage: str) -> "ShardReader":
        p = Path(root) / stage
        return cls(sorted(p.glob("shard-*.npz")))

    def __len__(self) -> int:
        total = 0
        for p in self.paths:
            with np.load(p, allow_pickle=True) as z:
                total += int(z["frames"].shape[0])
        return total

    def __iter__(self) -> Iterator[dict[str, np.ndarray]]:
        for p in self.paths:
            with np.load(p, allow_pickle=True) as z:
                yield {
                    "frames": z["frames"],
                    "actions": z["actions"],
                    "instructions": np.asarray(z["instructions"], dtype=str),
                    "reasonings": np.asarray(z["reasonings"], dtype=str),
                    "skills": np.asarray(z["skills"], dtype=str),
                }

    def load_all(self, limit: int | None = None) -> dict[str, np.ndarray]:
        frames, actions, instructions, reasonings, skills = [], [], [], [], []
        for shard in self:
            frames.append(shard["frames"])
            actions.append(shard["actions"])
            instructions.append(shard["instructions"])
            reasonings.append(shard["reasonings"])
            skills.append(shard["skills"])
            if limit and sum(len(f) for f in frames) >= limit:
                break
        if not frames:
            n = 0
            return {"frames": np.zeros((0, 90, 160), np.uint8),
                    "actions": np.zeros((0, NUM_KEYS + 5), np.float32),
                    "instructions": np.zeros(0, dtype=str),
                    "reasonings": np.zeros(0, dtype=str),
                    "skills": np.zeros(0, dtype=str)}
        out = {
            "frames": np.concatenate(frames),
            "actions": np.concatenate(actions).astype(np.float32),
            "instructions": np.concatenate(instructions),
            "reasonings": np.concatenate(reasonings),
            "skills": np.concatenate(skills),
        }
        if limit:
            for k in out:
                out[k] = out[k][:limit]
        return out


def corpus_report(root: str | Path) -> dict[str, Any]:
    """Summarise every stage: shards, frames, and the hours they represent."""
    root = Path(root)
    out: dict[str, Any] = {}
    for stage in STAGE_BY_NAME:
        reader = ShardReader.discover(root, stage)
        frames = len(reader) if reader.paths else 0
        hours = frames / 10.0 / 3600.0          # recorded at 10 Hz
        target = STAGE_BY_NAME[stage].target_hours
        out[stage] = {
            "shards": len(reader.paths),
            "frames": frames,
            "hours": round(hours, 4),
            "target_hours": target,
            "coverage": round(hours / target, 6) if target else 0.0,
        }
    return out


def format_corpus_report(report: dict[str, Any]) -> str:
    lines = ["| stage | shards | frames | hours | Lumine target | coverage |",
             "|---|---|---|---|---|---|"]
    for stage, r in report.items():
        lines.append(f"| {stage} | {r['shards']} | {r['frames']:,} | {r['hours']:.4f} | "
                     f"{r['target_hours']:,.0f} h | {r['coverage'] * 100:.4f}% |")
    return "\n".join(lines)
